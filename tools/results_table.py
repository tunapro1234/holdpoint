"""Build the README measurement table from results/bench-*.json.

    python -m tools.results_table            # print the table
    python -m tools.results_table --write    # replace the generated block in README.md
    python -m tools.results_table --check    # exit 1 if README.md is out of date

The table only shows what is in the files. A file without a provenance block is listed as "unverified".
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = "<!-- results-table:start (generated by tools/results_table.py, do not edit) -->"
END = "<!-- results-table:end -->"
FIXED = ("file", "device", "measured", "command")


def _cell(v) -> str:
    if v is None:
        return ""
    if isinstance(v, float):
        v = f"{v:.4g}"
    return str(v).replace("|", "\\|").replace("\n", " ")


def render(results_dir: Path) -> str:
    files = sorted(Path(results_dir).glob("bench-*.json"))
    if not files:
        return "_No benchmark results yet. `bench/bench.py` writes them to `results/bench-*.json`._"
    rows, keys = [], []
    for f in files:
        try:
            data = json.loads(f.read_text())
        except json.JSONDecodeError:
            rows.append({"file": f.name, "device": "unreadable JSON"})
            continue
        prov = data.get("provenance") or {}
        base = {
            "file": f.name,
            "device": prov.get("device", "unverified (no provenance)"),
            "measured": prov.get("timestamp", ""),
            "command": f"`{prov['command']}`" if prov.get("command") else "",
        }
        items = data.get("rows") or data.get("results") or [{}]
        if not isinstance(items, list):
            items = [{}]
        for item in items:
            item = item if isinstance(item, dict) else {}
            for k in item:
                if k not in keys and k not in FIXED:
                    keys.append(k)
            rows.append({**base, **item})
    cols = list(FIXED) + keys
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(_cell(r.get(c)) for c in cols) + " |" for r in rows]
    return "\n".join(lines)


def readme_block(text: str) -> str | None:
    if START not in text or END not in text:
        return None
    return text.split(START, 1)[1].split(END, 1)[0]


def write_readme(readme: Path, results_dir: Path) -> bool:
    text = readme.read_text()
    if readme_block(text) is None:
        raise ValueError(f"{readme} has no generated results block")
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    new = f"{head}{START}\n{render(results_dir)}\n{END}{tail}"
    changed = new != text
    readme.write_text(new)
    return changed


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", type=Path, default=ROOT / "results")
    ap.add_argument("--readme", type=Path, default=ROOT / "README.md")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    if args.write:
        print("README updated" if write_readme(args.readme, args.results) else "README already up to date")
        return 0
    if args.check:
        block = readme_block(args.readme.read_text())
        ok = block is not None and block.strip() == render(args.results).strip()
        print("up to date" if ok else "README results table is stale")
        return 0 if ok else 1
    print(render(args.results))
    return 0


if __name__ == "__main__":
    sys.exit(main())
